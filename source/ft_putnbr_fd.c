#include "libft.h"

void	ft_putnbr_fd(int n, int fd)
{
	long	nb;
	char	p;

	nb = n;
	if (nb < 0)
	{
		ft_putchar_fd('-', fd);
		nb = -nb;
	}
	if (nb < 10)
	{
		p = nb + '0';
		ft_putchar_fd(p, fd);
	}
	else
	{
		ft_putnbr_fd(nb / 10, fd);
		ft_putnbr_fd(nb % 10, fd);
	}
}

